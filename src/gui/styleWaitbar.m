function styleWaitbar(h)
% Apply a readable dark theme to a standard MATLAB waitbar.

if ~isgraphics(h)
    return;
end

background = [25 28 35] / 255;
foreground = [234 237 245] / 255;
accent = [191 172 255] / 255;

set(h, ...
    'Color', background, ...
    'NumberTitle', 'off', ...
    'Name', 'HoloDoppler — Progress');

% Progress label.
set(findall(h, 'Type', 'text'), ...
    'Color', foreground, ...
    'FontName', 'Arial', ...
    'FontSize', 11, ...
    'Interpreter', 'none');

% Progress-bar background and outline.
ax = findall(h, 'Type', 'axes');
set(ax, ...
    'Color', [35 39 49] / 255, ...
    'XColor', [100 110 130] / 255, ...
    'YColor', [100 110 130] / 255);

% Filled progress indicator.
set(findall(h, 'Type', 'patch'), ...
    'FaceColor', accent, ...
    'EdgeColor', accent);

drawnow;
end
